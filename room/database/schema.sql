-- Create room_reservation_db in PostgreSQL first, then run:
-- psql -U postgres -d room_reservation_db -f database/schema.sql

-- The room_user role must exist before running this script.
GRANT CONNECT ON DATABASE room_reservation_db TO room_user;

CREATE SCHEMA IF NOT EXISTS room_reservation;
SET search_path TO room_reservation, public;

CREATE TABLE IF NOT EXISTS users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(120) NOT NULL,
    email VARCHAR(190) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    contact_number VARCHAR(40) NOT NULL,
    role VARCHAR(16) NOT NULL DEFAULT 'guest'
        CHECK (role IN ('guest', 'staff', 'admin')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS user_profiles (
    user_id BIGINT PRIMARY KEY REFERENCES users(user_id) ON DELETE CASCADE,
    address VARCHAR(255),
    emergency_contact_name VARCHAR(120),
    emergency_contact_number VARCHAR(40),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS room_types (
    room_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL UNIQUE,
    description TEXT
);

INSERT INTO room_types (name, description) VALUES
    ('Standard', 'Comfortable essentials for a relaxing stay.'),
    ('Deluxe', 'Extra space and upgraded in-room amenities.'),
    ('Suite', 'A spacious suite with a separate living area.')
ON CONFLICT (name) DO NOTHING;

CREATE TABLE IF NOT EXISTS rooms (
    room_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_number VARCHAR(30) NOT NULL UNIQUE,
    room_type_id BIGINT NOT NULL REFERENCES room_types(room_type_id),
    capacity SMALLINT NOT NULL CHECK (capacity > 0),
    description TEXT NOT NULL,
    base_price NUMERIC(10,2) NOT NULL CHECK (base_price >= 0),
    availability_status VARCHAR(16) NOT NULL DEFAULT 'available'
        CHECK (availability_status IN ('available', 'maintenance', 'inactive')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

INSERT INTO rooms (room_number, room_type_id, capacity, description, base_price)
SELECT '101', room_type_id, 2,
       'A calm, well-appointed room with comfortable bedding and natural light.', 1800.00
FROM room_types WHERE name = 'Standard'
ON CONFLICT (room_number) DO NOTHING;
INSERT INTO rooms (room_number, room_type_id, capacity, description, base_price)
SELECT '202', room_type_id, 3,
       'A spacious deluxe room with a dedicated work area and generous storage.', 2800.00
FROM room_types WHERE name = 'Deluxe'
ON CONFLICT (room_number) DO NOTHING;
INSERT INTO rooms (room_number, room_type_id, capacity, description, base_price)
SELECT '301', room_type_id, 4,
       'A suite with room to unwind, a separate sitting area, and a balcony.', 4600.00
FROM room_types WHERE name = 'Suite'
ON CONFLICT (room_number) DO NOTHING;

CREATE TABLE IF NOT EXISTS amenities (
    amenity_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL UNIQUE
);

INSERT INTO amenities (name) VALUES
    ('Wi-Fi'), ('Air conditioning'), ('Breakfast'), ('Workspace'), ('Balcony'), ('Ocean view')
ON CONFLICT (name) DO NOTHING;

CREATE TABLE IF NOT EXISTS room_amenities (
    room_id BIGINT NOT NULL REFERENCES rooms(room_id) ON DELETE CASCADE,
    amenity_id BIGINT NOT NULL REFERENCES amenities(amenity_id) ON DELETE CASCADE,
    PRIMARY KEY (room_id, amenity_id)
);

INSERT INTO room_amenities (room_id, amenity_id)
SELECT r.room_id, a.amenity_id
FROM rooms r
JOIN amenities a ON
    (r.room_number = '101' AND a.name IN ('Wi-Fi', 'Air conditioning'))
    OR (r.room_number = '202' AND a.name IN ('Wi-Fi', 'Air conditioning', 'Workspace', 'Breakfast'))
    OR (r.room_number = '301' AND a.name IN ('Wi-Fi', 'Air conditioning', 'Balcony', 'Ocean view', 'Breakfast'))
ON CONFLICT (room_id, amenity_id) DO NOTHING;

CREATE TABLE IF NOT EXISTS room_images (
    image_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL REFERENCES rooms(room_id) ON DELETE CASCADE,
    image_url VARCHAR(500) NOT NULL,
    alt_text VARCHAR(160),
    sort_order SMALLINT NOT NULL DEFAULT 0 CHECK (sort_order >= 0)
);

INSERT INTO room_images (room_id, image_url, alt_text)
SELECT r.room_id, '../assets/images/room.svg', 'Sample room ' || r.room_number
FROM rooms r
WHERE NOT EXISTS (SELECT 1 FROM room_images i WHERE i.room_id = r.room_id);

CREATE TABLE IF NOT EXISTS user_preferences (
    preference_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(user_id) ON DELETE CASCADE,
    max_budget NUMERIC(10,2) CHECK (max_budget >= 0),
    guest_count SMALLINT CHECK (guest_count > 0),
    preferred_room_type_id BIGINT REFERENCES room_types(room_type_id) ON DELETE SET NULL,
    check_in_date DATE,
    check_out_date DATE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (check_in_date IS NULL OR check_out_date IS NULL OR check_out_date > check_in_date)
);

CREATE TABLE IF NOT EXISTS user_preference_amenities (
    preference_id BIGINT NOT NULL REFERENCES user_preferences(preference_id) ON DELETE CASCADE,
    amenity_id BIGINT NOT NULL REFERENCES amenities(amenity_id) ON DELETE CASCADE,
    PRIMARY KEY (preference_id, amenity_id)
);

CREATE TABLE IF NOT EXISTS reservation_status (
    status_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(32) NOT NULL UNIQUE
);

INSERT INTO reservation_status (name) VALUES
    ('Pending'), ('Approved'), ('Rejected'), ('Checked-In'), ('Completed'), ('Cancelled')
ON CONFLICT (name) DO NOTHING;

CREATE TABLE IF NOT EXISTS reservations (
    reservation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_reference VARCHAR(40) NOT NULL UNIQUE,
    user_id BIGINT NOT NULL REFERENCES users(user_id),
    room_id BIGINT NOT NULL REFERENCES rooms(room_id),
    status_id SMALLINT NOT NULL REFERENCES reservation_status(status_id),
    guest_count SMALLINT NOT NULL CHECK (guest_count > 0),
    check_in_date DATE NOT NULL,
    check_out_date DATE NOT NULL,
    nightly_rate NUMERIC(10,2) NOT NULL CHECK (nightly_rate >= 0),
    total_price NUMERIC(10,2) NOT NULL CHECK (total_price >= 0),
    guest_note VARCHAR(1000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_reservation_dates CHECK (check_out_date > check_in_date)
);

CREATE INDEX IF NOT EXISTS idx_reservation_dates
    ON reservations (room_id, check_in_date, check_out_date, status_id);

CREATE TABLE IF NOT EXISTS staff_approvals (
    approval_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id BIGINT NOT NULL REFERENCES reservations(reservation_id) ON DELETE CASCADE,
    staff_user_id BIGINT NOT NULL REFERENCES users(user_id),
    decision VARCHAR(16) NOT NULL CHECK (decision IN ('Approved', 'Rejected')),
    note VARCHAR(1000),
    reviewed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS room_pricing (
    room_pricing_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL REFERENCES rooms(room_id) ON DELETE CASCADE,
    price NUMERIC(10,2) NOT NULL CHECK (price >= 0),
    starts_on DATE NOT NULL,
    ends_on DATE NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT chk_room_pricing_dates CHECK (ends_on >= starts_on)
);

CREATE TABLE IF NOT EXISTS pricing_rules (
    pricing_rule_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    rule_type VARCHAR(16) NOT NULL
        CHECK (rule_type IN ('season', 'holiday', 'event', 'weekend', 'occupancy', 'promotion', 'custom')),
    adjustment_type VARCHAR(8) NOT NULL CHECK (adjustment_type IN ('percent', 'fixed')),
    adjustment_value NUMERIC(10,2) NOT NULL,
    min_occupancy_percent SMALLINT CHECK (min_occupancy_percent BETWEEN 1 AND 100),
    starts_on DATE NOT NULL,
    ends_on DATE NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT chk_pricing_rule_dates CHECK (ends_on >= starts_on)
);

CREATE TABLE IF NOT EXISTS qr_codes (
    qr_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id BIGINT NOT NULL UNIQUE REFERENCES reservations(reservation_id) ON DELETE CASCADE,
    qr_code_value CHAR(64) NOT NULL UNIQUE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    issued_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS checkin_logs (
    checkin_log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id BIGINT REFERENCES reservations(reservation_id) ON DELETE SET NULL,
    staff_user_id BIGINT REFERENCES users(user_id) ON DELETE SET NULL,
    scanned_value_prefix VARCHAR(16) NOT NULL,
    result VARCHAR(8) NOT NULL CHECK (result IN ('verified', 'denied')),
    message VARCHAR(255) NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS checkout_logs (
    checkout_log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id BIGINT NOT NULL REFERENCES reservations(reservation_id),
    staff_user_id BIGINT NOT NULL REFERENCES users(user_id),
    final_amount NUMERIC(10,2) NOT NULL CHECK (final_amount >= 0),
    note VARCHAR(1000),
    checked_out_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS transactions (
    transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id BIGINT NOT NULL REFERENCES reservations(reservation_id) ON DELETE CASCADE,
    transaction_type VARCHAR(16) NOT NULL
        CHECK (transaction_type IN ('reservation', 'approval', 'checkin', 'checkout', 'cancellation')),
    amount NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (amount >= 0),
    details VARCHAR(500),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

GRANT USAGE ON SCHEMA room_reservation TO room_user;
GRANT SELECT, INSERT, UPDATE, DELETE
    ON ALL TABLES IN SCHEMA room_reservation TO room_user;
GRANT USAGE, SELECT, UPDATE
    ON ALL SEQUENCES IN SCHEMA room_reservation TO room_user;

ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA room_reservation
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO room_user;
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA room_reservation
    GRANT USAGE, SELECT, UPDATE ON SEQUENCES TO room_user;
